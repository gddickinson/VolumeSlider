// Viewer page: open a 3D / 4D TIFF (or a shipped demo) and browse it like the plugin's 3D viewer. The file is read in
// this browser (tiff_reader.js) and never uploaded; in the local app it can also be read by tifffile to cross-check.
import { route, app, api, esc, isStatic, onLeave } from './core.js';
import { describeSample, fetchDemo, fileBuffer, readBuffer } from './loader.js';
import { mountViewer } from './viewer.js';
import { shared } from './state.js';

route('view', async (args, query) => {
  const demos = await api('/demos');
  app().innerHTML = `
  <h1 class="glow">Volume viewer</h1>
  <p class="lead">Open a 3D or 4D TIFF: slices in z, y and x, max projections, a 3D render and playback through the
  volumes. The file is read in this browser and never uploaded.</p>
  <div class="two openrow">
    <div><label class="drop" for="file" id="drop"><b>Choose a .tif / .tiff file</b><span>or drop it here</span>
      <input type="file" id="file" accept=".tif,.tiff,image/tiff"></label>
      <p class="small mute">Reads ImageJ hyperstacks (channels, slices, frames, spacing, unit), OME-TIFF (sizes,
      dimension order, physical sizes) and plain page stacks; classic or BigTIFF, uncompressed, LZW, Deflate or
      PackBits; 8/16/32-bit integers or 32/64-bit floats, one sample per pixel.</p>
      <div>${demos.map(d => `<button type="button" class="alt" data-demo="${d.id}">${esc(d.title)}</button>`).join('')}</div>
      <p class="small mute">Both demos are <b>synthetic</b> (generated by the repository's demo script), not microscope data.</p></div>
    <fieldset class="vox"><legend>Layout and units</legend>
      <label for="slices">slices per volume</label><input id="slices" type="number" min="0" step="1" value="0">
      <label for="vz">z step</label><input id="vz" type="number" min="0.0001" step="any" value="1">
      <label for="vy">y pixel</label><input id="vy" type="number" min="0.0001" step="any" value="1">
      <label for="vx">x pixel</label><input id="vx" type="number" min="0.0001" step="any" value="1">
      <label for="unit">unit</label><select id="unit"><option>µm</option><option>px</option></select>
      <p class="small mute span2">Slices per volume splits all pages, in file order, into volumes the way the
      plugin's "# of slices per volume" does (frame = slice + volume × slices; leftover pages are dropped).
      0 keeps the layout written in the file. Voxel sizes are filled in from the file when it has them.</p>
      ${isStatic() ? '' : '<button type="button" class="alt span2" id="pycheck" disabled>Cross-check with tifffile (Python)</button>'}
    </fieldset>
  </div>
  <div id="msg" aria-live="polite"></div>
  <div id="pymsg" aria-live="polite"></div>
  <div id="viewer" hidden></div>
  <p id="next" hidden><a class="btn alt" href="#/deskew?use=open">Deskew this stack →</a></p>`;
  const $ = s => document.getElementById(s);
  const viewer = mountViewer($('viewer'));
  onLeave(() => viewer.stop());
  let current = null;

  function show(s) {
    current = s;
    $('pymsg').innerHTML = '';
    ['vz', 'vy', 'vx'].forEach((id, i) => { $(id).value = +s.voxel[i].toPrecision(6); });
    $('unit').value = s.unit;
    const demo = demos.find(d => d.file === s.file);
    $('msg').innerHTML = `<p class="callout">${demo ? `<span class="badge">synthetic demo</span>${esc(demo.about)}<br>` : ''}${describeSample(s).map(esc).join('<br>')}</p>`;
    s.info = [['File', s.file], ['Read as', s.source]];
    $('viewer').hidden = false; $('next').hidden = false;
    if ($('pycheck')) $('pycheck').disabled = false;
    viewer.setSample(s);
  }

  async function load() {
    if (!shared.buf) return;
    shared.slices = Math.max(0, Math.floor(+$('slices').value || 0));
    try { show(await readBuffer(shared.buf, shared.name, { slicesPerVolume: shared.slices })); }
    catch (e) { $('msg').innerHTML = `<p class="err">Could not read ${esc(shared.name)}: ${esc(e.message)}</p>`; }
  }
  async function take(f) {
    if (!f) return;
    $('msg').innerHTML = `<p class="mute">Reading ${esc(f.name)}…</p>`;
    try { shared.buf = await fileBuffer(f); shared.name = f.name; $('slices').value = 0; load(); }
    catch (e) { $('msg').innerHTML = `<p class="err">${esc(e.message)}</p>`; }
  }
  async function demo(id) {
    const d = demos.find(x => x.id === id);
    $('msg').innerHTML = `<p class="mute">Loading ${esc(d.title)}…</p>`;
    shared.buf = await fetchDemo(d.file); shared.name = d.file; $('slices').value = 0;
    load();
  }
  $('file').addEventListener('change', e => take(e.target.files[0]));
  const drop = $('drop');
  drop.addEventListener('dragover', e => { e.preventDefault(); drop.classList.add('over'); });
  drop.addEventListener('dragleave', () => drop.classList.remove('over'));
  drop.addEventListener('drop', e => { e.preventDefault(); drop.classList.remove('over'); take(e.dataTransfer.files[0]); });
  document.querySelectorAll('[data-demo]').forEach(b => b.addEventListener('click', () => demo(b.dataset.demo)));
  $('slices').addEventListener('change', load);
  const units = () => {
    if (!current) return;
    current.voxel = ['vz', 'vy', 'vx'].map(id => Math.max(1e-4, +$(id).value || 1));
    current.unit = $('unit').value;
    current.info = current.info.filter(r => r[0] !== 'Scale').concat([['Scale', 'set on this page']]);
    viewer.setSample(current, { keepView: true });
  };
  ['vz', 'vy', 'vx', 'unit'].forEach(id => $(id).addEventListener('change', units));
  if ($('pycheck')) $('pycheck').addEventListener('click', async () => {
    const fd = new FormData();
    fd.append('file', new Blob([shared.buf]), shared.name);
    try {
      const r = await api(`/describe?slices_per_volume=${Math.max(0, +$('slices').value || 0)}`, { body: fd });
      const s = current, mine = { shape: [s.T, s.C, ...s.size].join(' × '), voxel: s.voxel.map(v => +v.toPrecision(6)).join(', '), unit: s.unit };
      const py = { shape: ['T', 'C', 'Z', 'Y', 'X'].map(k => r.shape[k]).join(' × '), voxel: r.voxel.map(v => +v.toPrecision(6)).join(', '), unit: r.unit };
      $('pymsg').innerHTML = (`<table class="check"><tr><th></th><th>browser</th><th>tifffile</th></tr>${
        ['shape', 'voxel', 'unit'].map(k => `<tr><td>${k}</td><td>${esc(mine[k])}</td><td class="${mine[k] === py[k] ? 'ok' : 'bad'}">${esc(py[k])}</td></tr>`).join('')}</table>`);
    } catch (e) { $('pymsg').innerHTML = `<p class="err">${esc(e.message)}</p>`; }
  });
  if (query.demo) demo(query.demo);
  else if (shared.buf) { $('slices').value = shared.slices || 0; load(); }
});

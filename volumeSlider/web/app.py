"""FastAPI web app for VolumeSlider: serves the front end in static/ and the JSON API under /api.

Run with `python run_web.py` (http://127.0.0.1:8233, local only). `scripts/build_static.py` exports every path in
STATIC_ENDPOINTS to JSON for the GitHub Pages site, so keep that list in step with the GET routes below.
The viewer and the shear transform run in the browser (static/); the API supplies the plugin's own defaults, the demo
descriptions read with tifffile, and the Python shear transform for cross-checking the browser's result.
"""
import hashlib
import re
from pathlib import Path

import numpy as np
from fastapi import FastAPI, File, HTTPException, UploadFile
from fastapi.responses import FileResponse
from fastapi.staticfiles import StaticFiles
from pydantic import BaseModel, Field

from ..shear_transform import (ARRAY_ORDERS, DEFAULT_DISPLAY_ORDER, DEFAULT_INPUT_ORDER, DEFAULT_SHIFT_FACTOR,
                               DEFAULT_THETA, DEFAULT_UPSAMPLE_AXIS, UPSAMPLE_AXIS_CHOICES, perform_shear_transform)
from .demo_volumes import CELL, SHEET
from .volume_io import describe, read_volume

STATIC = Path(__file__).resolve().parent / "static"
DEMO_DIR = STATIC / "demo"
ROOT = Path(__file__).resolve().parents[2]
MAX_UPLOAD = 512 * 1024 * 1024

DEMOS = {
    "cell": {"file": "synthetic_cell.tif", "title": "Synthetic cell (4D)",
             "about": "Synthetic, not microscope data: an ellipsoidal cell outline, a nucleus and puncta that drift "
                      "between three volumes. Generated by volumeSlider/web/demo_volumes.py (seed 1).",
             "params": {"voxel_um_zyx": list(CELL["voxel_um"])}},
    "sheet": {"file": "synthetic_lightsheet_raw.tif", "title": "Synthetic raw light-sheet scan",
              "about": "Synthetic, not microscope data: beads as a scanned oblique light sheet records them (one page "
                       "per scan step, rows along the tilted sheet), built so that the plugin's shear transform with "
                       "theta 45° and shift factor 2 returns round beads. Generated by "
                       "volumeSlider/web/demo_volumes.py (seed 2).",
              "params": {"theta": SHEET["theta"], "shift_factor": SHEET["shift_factor"],
                         "camera_pixel_um": SHEET["camera_px_um"]}},
}

app = FastAPI(title="VolumeSlider")
app.mount("/static", StaticFiles(directory=STATIC), name="static")


def _readme_overview():
    text = (ROOT / "README.md").read_text(encoding="utf-8")
    m = re.search(r"## Overview\s+(.+?)\n\n", text, re.S)
    feats = re.findall(r"^- \*\*(.+?)\*\*: (.+)$", text.split("## Installation")[0], re.M)
    plain = lambda t: re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", t).strip()  # noqa: E731  markdown links -> text
    return (plain(m.group(1)) if m else ""), [{"name": a, "text": plain(b)} for a, b in feats]


def _plugin_info():
    xml = (ROOT / "volumeSlider" / "info.xml").read_text(encoding="utf-8")
    get = lambda tag: (re.search(rf"<{tag}>\s*(.*?)\s*</{tag}>", xml, re.S) or [None, ""])[1]  # noqa: E731
    name = re.search(r'<plugin name="([^"]+)"', xml)
    return {"name": name.group(1) if name else "Volume slider", "version": get("version"), "author": get("author")}


@app.get("/", include_in_schema=False)
def index():
    return FileResponse(STATIC / "index.html")


@app.get("/api/info")
def info():
    """Project summary for the home and About pages (from README.md and the plugin's info.xml)."""
    overview, features = _readme_overview()
    return {"title": "VolumeSlider", "overview": overview, "features": features, "plugin": _plugin_info(),
            "array_orders": len(ARRAY_ORDERS), "demos": len(DEMOS)}


@app.get("/api/demos")
def demos():
    """The demo TIFFs shipped with the site, described by tifffile (shape, dtype, voxel size, value range)."""
    return [{"id": k, **{x: d[x] for x in ("file", "title", "about", "params")},
             "described": describe(str(DEMO_DIR / d["file"]))} for k, d in DEMOS.items()]


@app.get("/api/shear/defaults")
def shear_defaults():
    """The plugin's shear-transform settings: defaults and the 24 array orders of its drop-down menus."""
    return {"theta": DEFAULT_THETA, "shift_factor": DEFAULT_SHIFT_FACTOR, "input_order": DEFAULT_INPUT_ORDER,
            "display_order": DEFAULT_DISPLAY_ORDER, "array_orders": list(ARRAY_ORDERS.values()),
            "upsample_axis": DEFAULT_UPSAMPLE_AXIS, "upsample_axis_choices": UPSAMPLE_AXIS_CHOICES, "interpolate": False}


class ShearParams(BaseModel):
    theta: float = Field(SHEET["theta"], gt=0, lt=180)
    shift_factor: int = Field(SHEET["shift_factor"], ge=1, le=16)
    input_order: list[int] = DEFAULT_INPUT_ORDER
    display_order: list[int] = DEFAULT_DISPLAY_ORDER
    upsample_axis: int = Field(DEFAULT_UPSAMPLE_AXIS, ge=0, le=1)


def _shear_summary(p: ShearParams):
    for o in (p.input_order, p.display_order):
        if sorted(o) != [0, 1, 2, 3]:
            raise HTTPException(422, "array orders must be permutations of 0, 1, 2, 3")
    raw = read_volume(str(DEMO_DIR / DEMOS["sheet"]["file"]))["data"][:, 0]  # (t, z, y, x)
    B = raw.transpose(1, 0, 3, 2).astype(float)  # the plugin's (slices, volumes, x, y)
    try:
        E = perform_shear_transform(B, p.shift_factor, False, B.dtype, p.theta, inputArrayOrder=p.input_order,
                                    displayArrayOrder=p.display_order, upsample_axis=p.upsample_axis,
                                    progress=lambda m: None)
    except ValueError as e:
        raise HTTPException(422, f"the transform keeps no pixels for these settings ({e})")
    return {"params": p.model_dump(), "shape": list(E.shape), "sum": float(E.sum()),
            "nonzero": int(np.count_nonzero(E)),
            "sha256": hashlib.sha256(np.ascontiguousarray(E, "<f8").tobytes()).hexdigest()}


@app.get("/api/shear/demo")
def shear_demo():
    """The Python transform of the light-sheet demo at its intended settings (theta 45°, shift factor 2)."""
    return _shear_summary(ShearParams())


@app.post("/api/shear/check")
def shear_check(p: ShearParams):
    """The Python transform of the light-sheet demo at any settings, to compare with the browser's result."""
    return _shear_summary(p)


@app.post("/api/describe")
async def describe_upload(file: UploadFile = File(...), slices_per_volume: int = 0):
    """Read an uploaded TIFF with tifffile (local app only) and describe it, to cross-check the browser reader."""
    data = await file.read(MAX_UPLOAD + 1)
    if len(data) > MAX_UPLOAD:
        raise HTTPException(413, "file larger than 512 MB")
    try:
        return describe(data, slices_per_volume=max(0, slices_per_volume))
    except Exception as e:  # tifffile raises many types for bad files
        raise HTTPException(422, f"could not read the file: {e}")


# GET paths (without the /api prefix) written to the static site as api/<path>.json.
STATIC_ENDPOINTS = ["/info", "/demos", "/shear/defaults", "/shear/demo"]
